// Regenerates messages/REVIEW.md from the catalogues (ticket 018, FR-11).
// Usage: npx tsx scripts/i18n-review.ts
// Keeps the reviewer and status of rows whose hi/te text did not change; new or changed rows become `pending`.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { flattenMessages, parseReviewTable, REVIEW_HEADER, reviewRow, type ReviewRow } from "../lib/i18n/review";

const root = path.resolve(import.meta.dirname, "..");
const read = (locale: string) => JSON.parse(readFileSync(path.join(root, "messages", `${locale}.json`), "utf8"));
const reviewPath = path.join(root, "messages", "REVIEW.md");

const en = flattenMessages(read("en"));
const hi = flattenMessages(read("hi"));
const te = flattenMessages(read("te"));
const previous = new Map(
  (existsSync(reviewPath) ? parseReviewTable(readFileSync(reviewPath, "utf8")) : []).map((row) => [row.key, row]),
);

const rows: ReviewRow[] = Object.keys(en).map((key) => {
  const row = { key, en: en[key], hi: hi[key] ?? "", te: te[key] ?? "", reviewer: "", status: "pending" };
  const old = previous.get(key);
  if (old && old.en === row.en && old.hi === row.hi && old.te === row.te) {
    row.reviewer = old.reviewer;
    row.status = old.status;
  }
  return row;
});

const pending = rows.filter((r) => r.status !== "approved").length;
writeFileSync(
  reviewPath,
  `# Hindi and Telugu copy review

Generated by \`npx tsx scripts/i18n-review.ts\` from \`messages/*.json\` (ticket 018, FR-11). Rerun it after every
catalogue change; rows whose Hindi or Telugu text changed go back to \`pending\`.

Hindi and Telugu were first drafted by the worker that built ticket 018 (not a native-speaker review). A human
reviewer fluent in the language checks each row, then sets \`reviewer\` (name) and \`status\`
(\`pending\` | \`approved\` | \`changes-requested\`) in this file. All rows must be \`approved\` before the
Hyderabad pilot launch (launch checklist item).

Copy rules in every language: no word for "diagnose" or "diagnosis" except "not a diagnosis" (\`निदान नहीं\` /
\`నిర్ధారణ కాదు\`); never "HIPAA compliant"; \`DoctorNearMe\`, \`CareThread\`, \`ISAA\` stay in Latin script.

Rows: ${rows.length}. Not yet approved: ${pending}.

${REVIEW_HEADER}
${rows.map(reviewRow).join("\n")}
`,
);
console.log(`Wrote ${rows.length} rows to messages/REVIEW.md (${pending} not approved).`);
