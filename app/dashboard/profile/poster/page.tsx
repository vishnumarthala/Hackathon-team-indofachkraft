import type { Metadata } from "next";
import Link from "next/link";
import { redirect } from "next/navigation";
import { PrintButton } from "@/components/consent/PrintButton";
import { Alert } from "@/components/ui/Alert";
import { Card } from "@/components/ui/Card";
import { getUserRole, requirePageUser } from "@/lib/auth";
import { env } from "@/lib/env";
import { HTML_LANG, type Locale } from "@/lib/i18n/config";
import { getMessages } from "@/lib/i18n/messages";
import { getT } from "@/lib/i18n/server";
import { createTranslator } from "@/lib/i18n/translate";
import { getProfileByUserId } from "@/lib/providers";
import { countReferredCheckins, loadReferrerFresh, resolveReferrer } from "@/lib/referrals";
import { referralUrl, shortReferralUrl } from "@/lib/referrals/link";
import { referralQrSvg } from "@/lib/referrals/qr";

export const dynamic = "force-dynamic";

export async function generateMetadata(): Promise<Metadata> {
  const t = await getT("referrals");
  return { title: t("metaTitle") };
}

// The poster always carries all three languages, in this order, whatever the provider's UI language.
const POSTER_LOCALES: Locale[] = ["en", "te", "hi"];

// Ticket 054 FR-4: the paediatrician referral kit. A printable A4 waiting-room poster whose QR code opens the free
// check-in with "Referred by <name>" (`/screen?ref=<slug>`). Only the signed-in provider's own profile, and only while
// it is verified + listed (the same check `/screen` applies to the `ref`); otherwise an explanation. The provider sees
// an aggregate count of check-ins started from the poster in the last 30 days, nothing per family.
export default async function ReferralPosterPage() {
  const user = await requirePageUser();
  if ((await getUserRole(user.id)) === "guardian") redirect("/family");

  const t = await getT("referrals");
  const profile = await getProfileByUserId(user.id);
  const referrer = profile ? await resolveReferrer(profile.slug, loadReferrerFresh) : null;

  if (!profile || !referrer || referrer.profileId !== profile.id) {
    return (
      <div className="mx-auto max-w-3xl space-y-4 px-4 py-6">
        <h1 className="text-2xl font-semibold text-slate-900">{t("title")}</h1>
        <Alert tone="info" as="p" role="status" data-testid="poster-unavailable">
          {t("notAvailable")}
        </Alert>
        <Link href="/dashboard/profile" className="inline-flex min-h-11 items-center font-medium text-teal-700 underline">
          {t("backToProfile")}
        </Link>
      </div>
    );
  }

  const url = referralUrl(env.NEXT_PUBLIC_APP_URL, referrer.slug);
  const [svg, count] = await Promise.all([referralQrSvg(url), countReferredCheckins(profile.id)]);
  const poster = POSTER_LOCALES.map((locale) => ({ locale, t: createTranslator(locale, getMessages(locale), "referrals.poster") }));
  const [en] = poster;

  return (
    <div className="mx-auto max-w-4xl space-y-6 px-4 py-6 print:max-w-none print:p-0">
      <header className="space-y-3 print:hidden">
        <Link href="/dashboard/profile" className="inline-flex min-h-11 items-center text-sm font-medium text-teal-700 underline">
          {t("backToProfile")}
        </Link>
        <h1 className="text-2xl font-semibold text-slate-900">{t("title")}</h1>
        <p className="text-slate-700">{t("intro")}</p>
        <Card className="space-y-1" data-testid="poster-count">
          <p className="font-semibold text-slate-900">{t("count", { count })}</p>
          <p className="text-sm text-slate-600">{t("countHint")}</p>
        </Card>
        <PrintButton label={t("print")} />
      </header>

      <article
        className="poster-sheet mx-auto flex w-full max-w-[210mm] flex-col items-center gap-6 border border-slate-300 bg-white p-8 text-center text-slate-900 print:max-w-none print:border-0 print:p-0"
        data-testid="referral-poster"
      >
        <div className="space-y-4">
          {poster.map(({ locale, t: tp }) => (
            <div key={locale} lang={HTML_LANG[locale]} className="space-y-1">
              <p className={locale === "en" ? "text-3xl font-bold" : "text-2xl font-bold"}>{tp("headline")}</p>
              <p className="text-xl font-semibold text-teal-800">{tp("cta")}</p>
            </div>
          ))}
        </div>

        <div
          role="img"
          aria-label={en.t("qrLabel")}
          className="w-64 max-w-full print:w-[85mm] [&>svg]:h-auto [&>svg]:w-full"
          // Server-generated by `qrcode` from a validated referral URL (lib/referrals/qr.ts); no user input.
          dangerouslySetInnerHTML={{ __html: svg }}
        />

        <div className="space-y-1">
          <p className="text-sm text-slate-700">{poster.map(({ t: tp }) => tp("scan")).join(" · ")}</p>
          <p className="text-sm text-slate-700">{en.t("orType")}</p>
          <p className="text-lg font-semibold break-all" data-testid="poster-url">
            {shortReferralUrl(url)}
          </p>
        </div>

        <div className="space-y-1" data-testid="poster-referred-by">
          <p className="text-lg font-semibold">{en.t("referredBy", { name: referrer.displayName })}</p>
          <p className="text-sm text-slate-700">
            {poster.slice(1).map(({ locale, t: tp }, i) => (
              <span key={locale} lang={HTML_LANG[locale]}>
                {i > 0 ? " · " : null}
                {tp("referredBy", { name: referrer.displayName })}
              </span>
            ))}
          </p>
        </div>

        <ul className="space-y-1 border-t border-slate-300 pt-4 text-sm text-slate-800">
          {poster.map(({ locale, t: tp }) => (
            <li key={locale} lang={HTML_LANG[locale]}>
              {tp("footer")}
            </li>
          ))}
        </ul>
        <p className="text-xs text-slate-500">DoctorNearMe</p>
      </article>
    </div>
  );
}
