// Ticket 039 FR-4 / NFR-2: the signed prescription as a document. Pure and deterministic: the same version row
// (snapshots + items + signer + signed_at) always gives the same `content_md` (authoritative text, published through
// 024) and the same PDF (lib/rx/pdf.ts renders `rxDocumentLines`). Dates are formatted by hand in IST (no Intl), so a
// runtime or ICU upgrade cannot change a regenerated document.
import { escapeMarkdown } from "@/lib/iep/markdown";
import type { AllergyMatch, RxItem } from "./schema";

export type ChildSnapshot = {
  name: string;
  /** e.g. "4 years 2 months", or null when no date of birth / age is on record. */
  age: string | null;
  date_of_birth: string | null;
  weight_kg?: number | null;
};

export type PrescriberSnapshot = {
  name: string;
  qualifications: string | null;
  provider_type: string;
  council: string;
  council_state: string | null;
  registration_number: string;
  org: string;
  address: string | null;
};

/** `listed`: allergies on record; `none_known`: the family recorded "No known allergies"; `not_recorded`: UNKNOWN. */
export type AllergyStatus = "listed" | "none_known" | "not_recorded";

export type AllergiesSnapshot = {
  status: AllergyStatus;
  allergies: { substance: string; reaction: string; severity: string }[];
  /** Current medicines from the health profile at signing (for the record; not printed). */
  medications: { name: string; dose: string; frequency: string }[];
  health_profile_version: number;
  matches: AllergyMatch[];
  override_reason: string | null;
};

export type RxDocument = {
  child: ChildSnapshot;
  prescriber: PrescriberSnapshot;
  allergies: AllergiesSnapshot;
  items: RxItem[];
  advice: string | null;
  follow_up: string | null;
  /** ISO timestamp. */
  signed_at: string;
  version: number;
};

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const pad = (n: number) => String(n).padStart(2, "0");

/** `13 Nov 2026, 09:30 IST` (Asia/Kolkata has no DST: UTC+05:30). */
export function formatIst(iso: string | Date): string {
  const t = new Date(new Date(iso).getTime() + 330 * 60_000);
  return `${t.getUTCDate()} ${MONTHS[t.getUTCMonth()]} ${t.getUTCFullYear()}, ${pad(t.getUTCHours())}:${pad(t.getUTCMinutes())} IST`;
}

/** `13 Nov 2026` in IST. */
export function formatIstDate(iso: string | Date): string {
  return formatIst(iso).replace(/,.*$/, "");
}

const plural = (n: number, one: string) => `${n} ${one}${n === 1 ? "" : "s"}`;

/** Age on `at` from a `YYYY-MM-DD` date of birth (calendar months), e.g. `4 years 2 months`; null if unknown. */
export function ageOn(dateOfBirth: string | null, at: Date, fallbackMonths?: number | null): string | null {
  let months: number | null = null;
  const m = dateOfBirth ? /^(\d{4})-(\d{2})-(\d{2})$/.exec(dateOfBirth) : null;
  if (m) {
    const ist = new Date(at.getTime() + 330 * 60_000);
    months = (ist.getUTCFullYear() - Number(m[1])) * 12 + (ist.getUTCMonth() + 1 - Number(m[2]));
    if (ist.getUTCDate() < Number(m[3])) months -= 1;
    if (months < 0) months = null;
  } else if (fallbackMonths != null) {
    months = fallbackMonths;
  }
  if (months == null) return null;
  const years = Math.floor(months / 12);
  if (years === 0) return plural(months, "month");
  return months % 12 === 0 ? plural(years, "year") : `${plural(years, "year")} ${plural(months % 12, "month")}`;
}

export function councilLabel(council: string, state: string | null): string {
  switch (council) {
    case "NMC":
      return "National Medical Commission (NMC)";
    case "STATE_MEDICAL_COUNCIL":
      return state ? `${state} State Medical Council` : "State Medical Council";
    default:
      return council;
  }
}

/** FR-5 / 021: allergy status wording. Unknown is never shown as "none". */
export function allergyLine(a: AllergiesSnapshot): string {
  if (a.status === "listed") {
    return a.allergies
      .map((x) => `${x.substance}${x.severity && x.severity !== "unknown" ? ` (${x.severity}${x.reaction ? `, ${x.reaction}` : ""})` : x.reaction ? ` (${x.reaction})` : ""}`)
      .join("; ");
  }
  if (a.status === "none_known") return "No known allergies (as recorded by the family)";
  return "NOT RECORDED - allergy status unknown (the family has not recorded allergies)";
}

export function itemLine(item: RxItem): string {
  const name = [item.drug, item.strength, item.form].filter((s) => s && s.trim()).join(" ");
  const how = [item.dose, item.frequency, `for ${plural(item.duration_days, "day")}`].filter((s) => s && s.trim()).join(", ");
  const route = item.route ? ` (${item.route})` : "";
  return `${name} - ${how}${route}`;
}

export const AI_NOTE = "AI drafts are reviewed and signed by the prescriber.";
export const GENERATED_BY = "Generated by DoctorNearMe";

export function signatureLine(doc: Pick<RxDocument, "prescriber" | "signed_at">): string {
  return `Digitally generated on DoctorNearMe; signed by ${doc.prescriber.name} on ${formatIst(doc.signed_at)}`;
}

export function registrationLine(p: PrescriberSnapshot): string {
  return `${councilLabel(p.council, p.council_state)} - Reg. No. ${p.registration_number}`;
}

/** Free text kept as escaped paragraphs (one per non-empty line). */
export function paragraphs(value: string): string {
  return value
    .split(/\r?\n/)
    .map((line) => escapeMarkdown(line))
    .filter(Boolean)
    .join("\n\n");
}

/** Authoritative markdown of a signed version (FR-4). sha256 of it = `content_hash`. */
export function prescriptionMarkdown(doc: RxDocument): string {
  const p = doc.prescriber;
  const e = escapeMarkdown;
  const lines: string[] = [
    "# Prescription",
    "",
    `- **Prescriber:** ${e(p.name)}${p.qualifications ? `, ${e(p.qualifications)}` : ""}`,
    `- **Registration:** ${e(registrationLine(p))}`,
    `- **Clinic:** ${e(p.org)}${p.address ? `, ${e(p.address)}` : ""}`,
    `- **Date:** ${formatIst(doc.signed_at)}`,
    "",
    `- **Child:** ${e(doc.child.name)}${doc.child.age ? `, ${e(doc.child.age)}` : ", age not recorded"}`,
  ];
  if (doc.child.weight_kg != null) lines.push(`- **Weight:** ${doc.child.weight_kg} kg`);
  lines.push(`- **Allergies:** ${e(allergyLine(doc.allergies))}`);
  if (doc.allergies.override_reason) {
    const names = [...new Set(doc.allergies.matches.map((m) => m.drug))].join(", ");
    lines.push(`- **Allergy override:** ${e(names)} - ${e(doc.allergies.override_reason)}`);
  }
  lines.push("", "## Medicines", "");
  doc.items.forEach((item, i) => {
    // Two trailing spaces: a hard line break before the instructions line.
    lines.push(`${i + 1}. ${e(itemLine(item))}${item.instructions ? "  " : ""}`);
    if (item.instructions) lines.push(`   Instructions: ${e(item.instructions)}`);
  });
  if (doc.advice) lines.push("", "## Advice", "", paragraphs(doc.advice));
  if (doc.follow_up) lines.push("", "## Follow-up", "", paragraphs(doc.follow_up));
  lines.push("", "---", "", `${e(signatureLine(doc))}.`, "", `${AI_NOTE} ${GENERATED_BY}.`);
  return lines.join("\n") + "\n";
}

/** Published when a signed prescription is voided (024: a newer version replaces the old one for guardians). */
export function cancelledMarkdown(signedAt: string, voidedAt: string, prescriberName: string): string {
  return [
    "# Prescription cancelled",
    "",
    `The prescription signed by ${escapeMarkdown(prescriberName)} on ${formatIst(signedAt)} was cancelled by the prescriber on ${formatIst(voidedAt)}.`,
    "",
    "Do not use it. Contact your child's doctor if you have questions.",
    "",
  ].join("\n");
}
